  if (t.contains('جمع') || t.contains('المعلومات التي نقوم بجمعها') || t.contains('المعلومات')) {
    return Icons.assignment_ind_outlined;
  }
  if (t.contains('استخدام')) {
    return Icons.settings_suggest_outlined;
  }
  if (t.contains('مشاركة')) {
    return Icons.share_outlined;
  }
  if (t.contains('الخارجية') || t.contains('ثالث') || t.contains('أطراف')) {
    return Icons.extension_outlined;
  }
  if (t.contains('الاحتفاظ')) {
    return Icons.inventory_2_outlined;
  }
  if (t.contains('حماية') || t.contains('أمن')) {
    return Icons.security_outlined;
  }
  if (t.contains('حقوق')) {
    return Icons.verified_user_outlined;
  }
  if (t.contains('حذف') || t.contains('الحساب')) {
    return Icons.delete_forever_outlined;
  }
  if (t.contains('الأطفال')) {
    return Icons.child_care_outlined;
  }
