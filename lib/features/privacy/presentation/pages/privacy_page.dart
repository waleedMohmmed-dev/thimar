enum _SectionType { subTitle, bulletList, body }

class _PrivacySection {
  final String title;
  final IconData icon;
  final List<_SectionElement> elements;

  const _PrivacySection({
    required this.title,
    required this.icon,
    required this.elements,
  });
}

class _SectionElement {
  final _SectionType type;
  final String text;
  final List<String> bullets;

  const _SectionElement({
    required this.type,
    this.text = '',
    this.bullets = const [],
  });
}

IconData _getIconForSection(String title) {
  final t = title.toLowerCase();
  if (t.contains('سياسة') || t.contains('خصوصية') || t.contains('الخصوصية')) {
    return Icons.privacy_tip_outlined;
