class _RichText extends StatelessWidget {
  final String text;
  final TextStyle? style;

  const _RichText({required this.text, this.style});

  @override
  Widget build(BuildContext context) {
    final spans = _parseInline(text, style);
    return RichText(
      text: TextSpan(children: spans),
      textAlign: TextAlign.justify,
    );
  }

  List<TextSpan> _parseInline(String source, TextStyle? base) {
    final spans = <TextSpan>[];
    final regex = RegExp(r'\*\*(.+?)\*\*');
    int cursor = 0;

    for (final match in regex.allMatches(source)) {
      if (match.start > cursor) {
        spans.add(
          TextSpan(text: source.substring(cursor, match.start), style: base),
        );
      }
      spans.add(
        TextSpan(
          text: match.group(1),
          style: base?.copyWith(fontWeight: FontWeight.bold),
        ),
      );
      cursor = match.end;
    }

    if (cursor < source.length) {
      spans.add(TextSpan(text: source.substring(cursor), style: base));
    }

    if (spans.isEmpty) {
      spans.add(TextSpan(text: source, style: base));
    }

    return spans;
  }
}

