}

List<_PrivacySection> _parseSections(String content) {
  final lines = content.split('\n');
  final sections = <_PrivacySection>[];
  
  _PrivacySection? currentSection;
  final currentElements = <_SectionElement>[];
  
  final buffer = StringBuffer();
  final bullets = <String>[];

  void flushBody() {
    final text = buffer.toString().trim();
    if (text.isNotEmpty) {
      currentElements.add(_SectionElement(type: _SectionType.body, text: text));
      buffer.clear();
    }
  }

  void flushBullets() {
    if (bullets.isNotEmpty) {
      currentElements.add(
        _SectionElement(type: _SectionType.bulletList, bullets: List.of(bullets)),
      );
      bullets.clear();
    }
  }

  void flushSection() {
    flushBody();
    flushBullets();
    final section = currentSection;
    if (section != null && currentElements.isNotEmpty) {
      sections.add(
        _PrivacySection(
          title: section.title,
          icon: section.icon,
          elements: List.of(currentElements),
        ),
      );
      currentElements.clear();
    }
  }

  for (final line in lines) {
    final trimmed = line.trim();

    if (trimmed.startsWith('# ') && !trimmed.startsWith('## ')) {
      flushSection();
      final title = trimmed.substring(2).trim();
      currentSection = _PrivacySection(
        title: title,
        icon: _getIconForSection(title),
        elements: const [],
      );
    } else if (trimmed.startsWith('## ')) {
      flushBody();
      flushBullets();
      currentElements.add(
        _SectionElement(
          type: _SectionType.subTitle,
          text: trimmed.substring(3).trim(),
        ),
      );
    } else if (trimmed == '---') {
      // Skip dividers
    } else if (trimmed.startsWith('* ') || trimmed.startsWith('- ')) {
      flushBody();
      bullets.add(trimmed.substring(2).trim());
    } else if (trimmed.isEmpty) {
      flushBody();
      flushBullets();
    } else {
      flushBullets();
      buffer.write(trimmed);
      buffer.write(' ');
    }
  }

  flushSection();
  return sections;
}
